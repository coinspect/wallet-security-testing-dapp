import assert from "node:assert/strict";
import test from "node:test";
import { SIMPLE_SEND_ACTIONS, simpleTransaction } from "../src/utils/wallet-methods/simpleTransaction.mjs";
import { sourceLoader } from "./helpers/sourceHarness.mjs";

const load = sourceLoader();
const { handleAction } = load("src/utils/wallet-methods/actionMethods.js");
const { resolveCheckParams } = load("src/app/wizard/utils/resolveCheckParams.js");
const { buildWizardAuthBypassRequest } = load("src/utils/wallet-methods/authBypassPayloads.js");
const constants = load("src/utils/constants.js");
const checks = load("src/app/wizard/config/wizard.json").wizard.checks;
const account = `0x${"11".repeat(20)}`;
const hash = `0x${"ab".repeat(32)}`;
const target = constants.CHECKSUM_PROBE_BAD_CHECKSUM;

for (const platform of ["mobile", "extension"]) {
    for (const action of SIMPLE_SEND_ACTIONS) test(`${platform}/${action}: both formats preserve the exact recipient, amount and single-send behavior`, async () => {
        for (const dataMode of [undefined, "omitted_data"]) {
            const calls = [];
            const provider = { async request(args) {
                calls.push(structuredClone(args));
                if (["eth_requestAccounts", "eth_accounts"].includes(args.method)) return [account];
                if (args.method === "eth_chainId") return "0x89";
                if (args.method === "eth_sendTransaction") return hash;
                throw new Error(`Unexpected request ${args.method}`);
            } };
            await handleAction(platform, action, provider, { chain: "polygon", targetAddress: target, __transactionDataMode: dataMode });
            const sends = calls.filter((call) => call.method === "eth_sendTransaction");
            assert.deepEqual(sends, [{ method: "eth_sendTransaction", params: [{
                from: account, to: target, value: "0x0", ...(dataMode ? {} : { data: "0x" }),
            }] }]);
        }
    });

    test(`${platform}: no retry on rejection, internal error, timeout, pending or disconnect`, async () => {
        for (const error of [
            { code: 4001, message: "User rejected" },
            { code: -32000, message: "User canceled" },
            { code: -32603, message: "The data couldn’t be read because it is missing." },
            { code: -32002, message: "Request already pending" },
            { code: 4900, message: "Disconnected" },
            { message: "Request timed out" },
        ]) {
            const calls = [];
            const provider = { async request(args) {
                calls.push(args);
                if (["eth_requestAccounts", "eth_accounts"].includes(args.method)) return [account];
                if (args.method === "eth_chainId") return "0x89";
                throw error;
            } };
            try { await handleAction(platform, "sendFamiliarRecipientTransaction", provider); } catch { /* Rejection is expected. */ }
            assert.equal(calls.filter((call) => call.method === "eth_sendTransaction").length, 1);
            assert.equal(calls.at(-1).params[0].data, "0x");
        }
    });
}

test("every configured simple send documents the new data field, including explorer links", () => {
    const found = new Set();
    for (const check of Object.values(checks)) for (const step of check.steps) {
        const action = step.ui?.content?.button?.action;
        if (!SIMPLE_SEND_ACTIONS.has(action)) continue;
        const resolved = resolveCheckParams(step);
        assert.equal(resolved.parameters.data, "0x");
        assert.equal(resolved.parameters.method, "eth_sendTransaction");
        assert.equal(resolved.parameters.value, "0x0");
        found.add(action);
    }
    assert.deepEqual(found, SIMPLE_SEND_ACTIONS);
});

test("auth-bypass self-send and parameter registry use the explicit empty-data envelope", () => {
    const request = buildWizardAuthBypassRequest({ method: "eth_sendTransaction", account });
    assert.deepEqual(request, { method: "eth_sendTransaction", params: [{ from: account, to: account, value: "0x0", data: "0x" }] });
    // These entries are generated by the same builder, not separately edited fixtures.
    const documented = constants.testParams.find((entry) => entry.key === "bypass_eth_send_transaction").full[0];
    assert.equal(documented.data, "0x");
    assert.equal(documented.value, "0x0");
    assert.equal(documented.from, documented.to);
});

test("unrecognized formats fail closed rather than changing arbitrary calldata", () => {
    assert.throws(() => simpleTransaction(account, target, "0x1234"), /Unknown transaction data format/);
});
